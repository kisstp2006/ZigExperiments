/// Builds the font atlas texture (white glyphs on transparent background).
pub fn buildAtlasTexture(alloc: std.mem.Allocator) !Texture {
    var pixels = try alloc.alloc(u8, atlas_w * atlas_h * 4);
    defer alloc.free(pixels);
    @memset(pixels, 0);

    var c: usize = 0;
    while (c < 95) : (c += 1) {
        const col: usize = c % 16;
        const row: usize = c / 16;
        const origin_x = col * 6;
        const origin_y = row * 8 + 1; // 1px top padding
        for (glyphs[c], 0..) |line, gy| {
            var gx: usize = 0;
            while (gx < 5) : (gx += 1) {
                if (line & (@as(u8, 1) << @intCast(4 - gx)) != 0) {
                    const px = origin_x + gx;
                    const py = origin_y + gy;
                    const idx = (py * atlas_w + px) * 4;
                    pixels[idx + 0] = 255;
                    pixels[idx + 1] = 255;
                    pixels[idx + 2] = 255;
                    pixels[idx + 3] = 255;
                }
            }
        }
    }

    const id = try gl.createTextureRGBA(atlas_w, atlas_h, pixels, true);
    return .{ .id = id, .width = atlas_w, .height = atlas_h };
}

/// UV rectangle (in 0..1 texture space) for one glyph cell.
pub fn glyphUv(c: u8) ?[4]f32 {
    if (c < 32 or c > 126) return null;
    const idx: usize = c - 32;
    const col: f32 = @floatFromInt(idx % 16);
    const row: f32 = @floatFromInt(idx / 16);
    const uv_left = (col * cell_w) / @as(f32, @floatFromInt(atlas_w));
    const uv_right = ((col + 1) * cell_w) / @as(f32, @floatFromInt(atlas_w));
    const uv_top = (row * cell_h) / @as(f32, @floatFromInt(atlas_h));
    const uv_bottom = ((row + 1) * cell_h) / @as(f32, @floatFromInt(atlas_h));
    return .{ uv_left, uv_top, uv_right, uv_bottom };
}

pub fn glyphAdvance(font_size: f32) f32 {
    return font_size * (cell_w / cell_h);
}
